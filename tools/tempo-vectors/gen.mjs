// Generates tests/tempo_vectors.h: Tempo charge transactions built and signed
// by ox, the library mppx uses, from fixed inputs.
//
//   cd tools/tempo-vectors && npm install && node gen.mjs > ../../tests/tempo_vectors.h
//
// The attribution memo follows mppx 0.13.4 (src/tempo/Attribution.ts).

import { AbiFunction, Address, Bytes, Hash, Hex, P256 } from 'ox'
import { SignatureEnvelope, TxEnvelopeTempo } from 'ox/tempo'

const maxUint256 = 2n ** 256n - 1n

// Test-only key. Never fund it.
const privateKey = '0x1111111111111111111111111111111111111111111111111111111111111111'
const publicKey = P256.getPublicKey({ privateKey })
const keyAddress = Address.fromPublicKey(publicKey)
const owner = '0xa11ce00000000000000000000000000000000001'
const token = '0x20c0000000000000000000000000000000000000'
const recipient = '0x742d35cc6634c0532925a3b844bc9e7595f8fe00'

const transferWithMemo = AbiFunction.from(
  'function transferWithMemo(address to, uint256 amount, bytes32 memo)',
)
const transfer = AbiFunction.from('function transfer(address to, uint256 amount)')

function attributionMemo({ serverId, clientId, challengeId }) {
  const tag = Hex.slice(Hash.keccak256(Bytes.fromString('mpp'), { as: 'Hex' }), 0, 4)
  const fingerprint = (value) =>
    Hex.toBytes(Hex.slice(Hash.keccak256(Bytes.fromString(value), { as: 'Hex' }), 0, 10))
  const buf = new Uint8Array(32)
  buf.set(Hex.toBytes(tag), 0)
  buf[4] = 0x01
  buf.set(fingerprint(serverId), 5)
  if (clientId) buf.set(fingerprint(clientId), 15)
  buf.set(
    Hex.toBytes(Hex.slice(Hash.keccak256(Bytes.fromString(challengeId), { as: 'Hex' }), 0, 7)),
    25,
  )
  return Hex.fromBytes(buf)
}

