// Generates tests/tempo_vectors.h: Tempo charge transactions built and signed
// by ox, the library mppx uses, from fixed inputs.
//
//   cd tools/tempo-vectors && npm install && node gen.mjs > ../../tests/tempo_vectors.h
//
// The attribution memo follows mppx 0.13.4 (src/tempo/Attribution.ts).

import { AbiFunction, Address, Bytes, Hash, Hex, P256 } from 'ox'
import { SignatureEnvelope, TxEnvelopeTempo } from 'ox/tempo'

const maxUint256 = 2n ** 256n - 1n

// Test-only key. Never fund it.
const privateKey = '0x1111111111111111111111111111111111111111111111111111111111111111'
const publicKey = P256.getPublicKey({ privateKey })
const keyAddress = Address.fromPublicKey(publicKey)
const owner = '0xa11ce00000000000000000000000000000000001'
const token = '0x20c0000000000000000000000000000000000000'
const recipient = '0x742d35cc6634c0532925a3b844bc9e7595f8fe00'

const transferWithMemo = AbiFunction.from(
  'function transferWithMemo(address to, uint256 amount, bytes32 memo)',
)

function attributionMemo({ serverId, clientId, challengeId }) {
  const tag = Hex.slice(Hash.keccak256(Bytes.fromString('mpp'), { as: 'Hex' }), 0, 4)
  const fingerprint = (value) =>
    Hex.toBytes(Hex.slice(Hash.keccak256(Bytes.fromString(value), { as: 'Hex' }), 0, 10))
  const buf = new Uint8Array(32)
  buf.set(Hex.toBytes(tag), 0)
  buf[4] = 0x01
  buf.set(fingerprint(serverId), 5)
  if (clientId) buf.set(fingerprint(clientId), 15)
  buf.set(
    Hex.toBytes(Hex.slice(Hash.keccak256(Bytes.fromString(challengeId), { as: 'Hex' }), 0, 7)),
    25,
  )
  return Hex.fromBytes(buf)
}

const cases = [
  {
    name: 'fee_payer',
    chainId: 42431,
    amount: 1000n,
    memo: attributionMemo({ serverId: 'api.example.com', challengeId: 'ch_abc123' }),
    feePayer: true,
    gas: 120000n,
    maxFeePerGas: 30000000000n,
    maxPriorityFeePerGas: 1000000000n,
    validBefore: 1760400025,
    validAfter: 1700000000,
  },
  {
    name: 'self_paid',
    chainId: 4217,
    amount: 2500000n,
    memo: attributionMemo({ serverId: 'mpp.dev', clientId: 'transponder', challengeId: 'x7Tg2pLqR9mKvNwY3hBcZa' }),
    feePayer: false,
    feeToken: token,
    gas: 95000n,
    maxFeePerGas: 25000000000n,
    maxPriorityFeePerGas: 0n,
    validBefore: 1760400100,
    validAfter: undefined,
  },
]

const out = []
const hex = (h) => '"' + h.slice(2) + '"'
const bytesOf = (h) => (h.length - 2) / 2

out.push('/* Generated by tools/tempo-vectors/gen.mjs with ox 0.14.45. Do not edit. */')
out.push('#ifndef TRANSPONDER_TEMPO_VECTORS_H')
out.push('#define TRANSPONDER_TEMPO_VECTORS_H')
out.push('')
out.push('#include <stdint.h>')
out.push('')
out.push('/* Test-only P-256 key (private key 0x11 x 32), never funded. */')
out.push(`#define TV_PUBLIC_KEY ${hex(Hex.concat(Hex.fromNumber(publicKey.x, { size: 32 }), Hex.fromNumber(publicKey.y, { size: 32 })))}`)
out.push(`#define TV_KEY_ADDRESS ${hex(keyAddress.toLowerCase())}`)
out.push(`#define TV_OWNER ${hex(owner)}`)
out.push(`#define TV_TOKEN ${hex(token)}`)
out.push(`#define TV_RECIPIENT ${hex(recipient)}`)
out.push(`#define TV_TRANSFER_WITH_MEMO_SELECTOR ${hex(AbiFunction.getSelector(transferWithMemo))}`)
out.push('')
out.push('typedef struct {')
out.push('    const char *name;')
out.push('    uint64_t chain_id, gas, max_fee_per_gas, max_priority_fee_per_gas, valid_before, valid_after;')
out.push('    int fee_payer, has_valid_after;')
out.push('    const char *amount_decimal, *memo, *calldata, *sender_hash, *keychain_digest;')
out.push('    const char *sig_r, *sig_s, *envelope;')
out.push('} tempo_vector;')
out.push('')
out.push('static const tempo_vector TEMPO_VECTORS[] = {')

for (const c of cases) {
  const data = AbiFunction.encodeData(transferWithMemo, [recipient, c.amount, c.memo])
  const envelope = TxEnvelopeTempo.from({
    chainId: c.chainId,
    calls: [{ to: token, data }],
    gas: c.gas,
    maxFeePerGas: c.maxFeePerGas,
    maxPriorityFeePerGas: c.maxPriorityFeePerGas,
    nonceKey: maxUint256,
    nonce: 0n,
    validBefore: c.validBefore,
    ...(c.validAfter !== undefined ? { validAfter: c.validAfter } : {}),
    ...(c.feePayer ? { feePayerSignature: null } : { feeToken: c.feeToken }),
  })
  const senderHash = TxEnvelopeTempo.getSignPayload(envelope)
  const digest = TxEnvelopeTempo.getSignPayload(envelope, { from: owner })
  const signature = P256.sign({ payload: digest, privateKey })
  const keychain = SignatureEnvelope.from({
    type: 'keychain',
    version: 'v2',
    userAddress: owner,
    inner: SignatureEnvelope.from({ signature, publicKey, prehash: false }),
  })
  const serialized = TxEnvelopeTempo.serialize(envelope, { signature: keychain })

  // Sanity: the signature verifies, and ox reads the envelope back.
  if (!P256.verify({ payload: digest, publicKey, signature })) throw new Error('bad signature')
  TxEnvelopeTempo.deserialize(serialized)

  out.push(`    {"${c.name}", ${c.chainId}u, ${c.gas}u, ${c.maxFeePerGas}u, ${c.maxPriorityFeePerGas}u, ${c.validBefore}u, ${c.validAfter ?? 0}u,`)
  out.push(`     ${c.feePayer ? 1 : 0}, ${c.validAfter !== undefined ? 1 : 0}, "${c.amount}", ${hex(c.memo)},`)
  out.push(`     ${hex(data)},`)
  out.push(`     ${hex(senderHash)}, ${hex(digest)},`)
  out.push(`     ${hex(Hex.fromNumber(signature.r, { size: 32 }))}, ${hex(Hex.fromNumber(signature.s, { size: 32 }))},`)
  out.push(`     ${hex(serialized)}}, /* ${bytesOf(serialized)} bytes */`)
}

out.push('};')
out.push('')
out.push('#endif')
out.push('')
process.stdout.write(out.join('\n'))
