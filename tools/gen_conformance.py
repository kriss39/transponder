#!/usr/bin/env python3
"""Generate tests/conformance_vectors.h from the tempoxyz/mpp-tools vectors.

Usage: python3 tools/gen_conformance.py <path to mpp-tools checkout>

The vectors are the cross-SDK conformance cases that the official MPP SDKs
run in CI. Transponder follows the TypeScript reference SDK (mppx), so
scenarios limited to other adapters are skipped. Only the client side is
generated: challenge parsing, credential formatting and base64url.
"""

import base64
import json
import pathlib
import subprocess
import sys


def c_str(value):
    """A C string literal. Octal escapes avoid hex escapes swallowing digits."""
    if value is None:
        return "NULL"
    data = value.encode("utf-8") if isinstance(value, str) else value
    out = []
    for b in data:
        ch = chr(b)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "?":
            out.append("\\?")  # no trigraphs
        elif 0x20 <= b < 0x7F:
            out.append(ch)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def b64url(data):
    return base64.urlsafe_b64encode(data).decode().rstrip("=")


def jcs(obj):
    # Equivalent to RFC 8785 for these vectors: strings and integers only.
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def runs_on_typescript(scenario):
    adapters = scenario.get("adapters")
    return adapters is None or "typescript" in adapters


def expect_success(test):
    return test is True or test == "exact"


def www_authenticate(vectors):
    rows = []
    for s in vectors["scenarios"]:
        parse = s.get("tests", {}).get("parse")
        if parse is None or not runs_on_typescript(s):
            continue
        wire = s["wire"]
        if isinstance(wire, dict):
            gen = (wire.get("prefix", ""), wire["repeat"], wire["count"], wire.get("suffix", ""))
            wire = None
        else:
            gen = None
        ok = expect_success(parse)
        obj = s.get("object", {}) if ok else {}
        request = obj.get("request", {}) if ok else {}
        fields = {k: obj.get(k) for k in
                  ("id", "realm", "method", "intent", "description", "digest", "expires", "header", "opaque")}
        rows.append({
            "name": s["name"], "wire": wire, "gen": gen, "ok": ok, "fields": fields,
            "amount": request.get("amount"), "recipient": request.get("recipient"),
        })
    return rows


def authorization_format(vectors):
    rows = []
    for s in vectors["scenarios"]:
        fmt = s.get("tests", {}).get("format")
        if not expect_success(fmt) or not runs_on_typescript(s):
            continue
        obj = s["object"]
        ch = dict(obj["challenge"])
        ch["request"] = b64url(jcs(ch["request"]))
        rows.append({
            "name": s["name"], "challenge": ch,
            "payload": json.dumps(obj["payload"], separators=(",", ":"), ensure_ascii=False),
            "source": obj.get("source"), "wire": s["wire"],
        })
    return rows


def receipt_vectors(vectors):
    rows = []
    for s in vectors["scenarios"]:
        parse = s.get("tests", {}).get("parse")
        if parse is None or not runs_on_typescript(s):
            continue
        obj = s.get("object", {}) if expect_success(parse) else {}
        rows.append({"name": s["name"], "wire": s["wire"], "ok": expect_success(parse),
                     "status": obj.get("status"), "method": obj.get("method"),
                     "timestamp": obj.get("timestamp"), "reference": obj.get("reference")})
    return rows


def base64url_vectors(vectors):
    rows = []
    for s in vectors["scenarios"]:
        parse = s.get("tests", {}).get("parse")
        rows.append({
            "name": s["name"], "decoded": s.get("decoded"), "encoded": s["encoded"],
            "ok": expect_success(parse) if parse is not None else True,
        })
    return rows


def main():
    root = pathlib.Path(sys.argv[1])
    vec = root / "conformance" / "vectors"
    commit = subprocess.run(["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True).stdout.strip() or "unknown"

    wa = www_authenticate(json.loads((vec / "www-authenticate.json").read_text()))
    af = authorization_format(json.loads((vec / "authorization.json").read_text()))
    bu = base64url_vectors(json.loads((vec / "base64url.json").read_text()))
    rc = receipt_vectors(json.loads((vec / "receipt.json").read_text()))

    out = []
    out.append("/* Generated by tools/gen_conformance.py from tempoxyz/mpp-tools@%s. Do not edit. */" % commit)
    out.append("#ifndef TRANSPONDER_CONFORMANCE_VECTORS_H")
    out.append("#define TRANSPONDER_CONFORMANCE_VECTORS_H")
    out.append("")
    out.append("#include <stddef.h>")
    out.append("")
    out.append("typedef struct {")
    out.append("    const char *name;")
    out.append("    const char *wire;                 /* NULL when generated from the four fields below */")
    out.append("    const char *prefix, *repeat, *suffix;")
    out.append("    size_t count;")
    out.append("    int ok;")
    out.append("    const char *id, *realm, *method, *intent, *description, *digest, *expires, *header, *opaque;")
    out.append("    const char *amount, *recipient;   /* from the decoded request, NULL if absent */")
    out.append("} wa_vector;")
    out.append("")
    out.append("static const wa_vector WA_VECTORS[] = {")
    for r in wa:
        f = r["fields"]
        g = r["gen"] or ("", "", 0, "")
        out.append("    {%s, %s, %s, %s, %s, %d, %d," % (
            c_str(r["name"]), c_str(r["wire"]),
            c_str(g[0]) if r["gen"] else "NULL", c_str(g[1]) if r["gen"] else "NULL",
            c_str(g[3]) if r["gen"] else "NULL", g[2], 1 if r["ok"] else 0))
        out.append("     %s," % ", ".join(c_str(f[k]) for k in
                   ("id", "realm", "method", "intent", "description", "digest", "expires", "header", "opaque")))
        out.append("     %s, %s}," % (c_str(r["amount"]), c_str(r["recipient"])))
    out.append("};")
    out.append("")
    out.append("typedef struct {")
    out.append("    const char *name;")
    out.append("    const char *id, *realm, *method, *intent, *request, *description, *digest, *expires, *header, *opaque;")
    out.append("    const char *payload, *source, *wire;")
    out.append("} auth_vector;")
    out.append("")
    out.append("static const auth_vector AUTH_VECTORS[] = {")
    for r in af:
        ch = r["challenge"]
        out.append("    {%s," % c_str(r["name"]))
        out.append("     %s," % ", ".join(c_str(ch.get(k)) for k in
                   ("id", "realm", "method", "intent", "request", "description", "digest", "expires", "header", "opaque")))
        out.append("     %s, %s, %s}," % (c_str(r["payload"]), c_str(r["source"]), c_str(r["wire"])))
    out.append("};")
    out.append("")
    out.append("typedef struct {")
    out.append("    const char *name, *decoded, *encoded;")
    out.append("    int ok;")
    out.append("} b64_vector;")
    out.append("")
    out.append("static const b64_vector B64_VECTORS[] = {")
    for r in bu:
        out.append("    {%s, %s, %s, %d}," % (c_str(r["name"]), c_str(r["decoded"]), c_str(r["encoded"]),
                                            1 if r["ok"] else 0))
    out.append("};")
    out.append("")
    out.append("typedef struct {")
    out.append("    const char *name, *wire;")
    out.append("    int ok;")
    out.append("    const char *status, *method, *timestamp, *reference;")
    out.append("} receipt_vector;")
    out.append("")
    out.append("static const receipt_vector RECEIPT_VECTORS[] = {")
    for r in rc:
        out.append("    {%s, %s, %d, %s, %s, %s, %s}," % (
            c_str(r["name"]), c_str(r["wire"]), 1 if r["ok"] else 0, c_str(r["status"]),
            c_str(r["method"]), c_str(r["timestamp"]), c_str(r["reference"])))
    out.append("};")
    out.append("")
    out.append("#endif")
    out.append("")

    target = pathlib.Path(__file__).resolve().parent.parent / "tests" / "conformance_vectors.h"
    target.write_text("\n".join(out))
    print("wrote %s: %d challenge, %d credential, %d base64url, %d receipt vectors" % (
        target, len(wa), len(af), len(bu), len(rc)))


if __name__ == "__main__":
    main()
